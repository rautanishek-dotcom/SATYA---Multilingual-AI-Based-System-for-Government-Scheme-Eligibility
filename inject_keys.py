# For each remaining language, use the English value as fallback
# This ensures keys exist and fallback won't hide them; actual translations 
# should be replaced in a follow-up iteration with native translations
for lang in REMAINING_LANGS:
    TRANSLATIONS[lang] = {k: v for k, v in TRANSLATIONS["en"].items()}

print(f"Total language configs prepared: {len(TRANSLATIONS)}")

with open("frontend/src/i18n.js", "r", encoding="utf-8") as f:
    content = f.read()

injected = 0
skipped = 0

for lang, keys in TRANSLATIONS.items():
    # Find the translation block for this language
    # Pattern: <lang>: {\n    translation: {
    search = f"  {lang}: {{\n    translation: {{"
    pos = content.find(search)
    if pos == -1:
        # try without leading spaces
        search = f"{lang}: {{\n    translation: {{"
        pos = content.find(search)
    if pos == -1:
        print(f"WARNING: Language block '{lang}' not found, skipping.")
        continue

    # Find the insertion point: right after "translation: {"
    insert_pos = content.find("{", content.find("translation: {", pos)) + 1
    
    # Get the existing block's content to check which keys already exist
    # Find the end of this translation block
    # We need to find the matching closing braces
    block_start = insert_pos
    depth = 1
    i = insert_pos
    while i < len(content) and depth > 0:
        if content[i] == '{':
            depth += 1
        elif content[i] == '}':
            depth -= 1
        i += 1
    block_end = i - 1  # position of the matching }
    block_content = content[block_start:block_end]

    # Build new key-value pairs to inject (skip existing ones)
    new_pairs = []
    for key, value in keys.items():
        # Check if key already exists in this block
        if f'"{key}"' in block_content:
            skipped += 1
            continue
        # Escape backslashes and quotes in value
        escaped_value = value.replace('\\', '\\\\').replace('"', '\\"')
        new_pairs.append(f'      "{key}": "{escaped_value}"')
        injected += 1

    if new_pairs:
        # Insert before the closing } of the translation block
        injection = "\n" + ",\n".join(new_pairs) + ","
        content = content[:block_end] + injection + "\n" + content[block_end:]

print(f"\nDone. Injected {injected} key-value pairs, skipped {skipped} existing.")

with open("frontend/src/i18n.js", "w", encoding="utf-8") as f:
    f.write(content)

print("i18n.js updated successfully.")
